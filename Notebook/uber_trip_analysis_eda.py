trip_df.rename(columns={
    'Location':'Pickup Location',
    'City':'Pickup City'
}, inplace=True)

trip_df.drop('LocationID', axis=1, inplace=True)


# Dropoff Location
trip_df = trip_df.merge(
    location_df,
    left_on='DOLocationID',
    right_on='LocationID',
    how='left'
)

trip_df.rename(columns={
    'Location':'Dropoff Location',
    'City':'Dropoff City'
}, inplace=True)

trip_df.drop('LocationID', axis=1, inplace=True)

