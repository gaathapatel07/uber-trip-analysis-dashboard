# ============================================================
# Feature Engineering
# ============================================================

# Date
trip_df['Pickup Date'] = trip_df['Pickup Time'].dt.date

# Time
trip_df['Pickup Hour'] = trip_df['Pickup Time'].dt.hour

# Month
trip_df['Month'] = trip_df['Pickup Time'].dt.month_name()

# Day Name
trip_df['Day Name'] = trip_df['Pickup Time'].dt.day_name()

# Weekday Number
trip_df['Weekday'] = trip_df['Pickup Time'].dt.weekday

# Weekend / Weekday
trip_df['Trip Day'] = np.where(
    trip_df['Weekday'] >= 5,
    'Weekend',
    'Weekday'
)

# Trip Duration (minutes)
trip_df['Trip Duration (min)'] = (
    trip_df['Drop Off Time'] - trip_df['Pickup Time']
).dt.total_seconds() / 60

# Day / Night Trip
trip_df['Trip (Day/Night)'] = np.where(
    (trip_df['Pickup Hour'] >= 6) &
    (trip_df['Pickup Hour'] < 18),
    'Day Trip',
    'Night Trip'
)

# Total Fare
trip_df['Total Fare'] = trip_df['fare_amount'] + trip_df['Surge Fee']

# Fare Per Mile
trip_df['Fare Per Mile'] = (
    trip_df['Total Fare'] / trip_df['trip_distance']
)

# Replace infinite values
trip_df.replace([np.inf, -np.inf], np.nan, inplace=True)

